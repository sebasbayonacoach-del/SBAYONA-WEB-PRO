import {test,expect} from '@playwright/test'

for(const [name,width,height] of [['desktop',1440,900],['mobile',390,844]]){
 test('movement catalog / '+name,async({page})=>{
  await page.setViewportSize({width,height})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/movimiento-adaptado')
  await expect(page.getByRole('heading',{level:1})).toContainText('TU CUERPO NO ES UN DIAGNÓSTICO')
  const cards=page.locator('.bayona-adapted__group')
  await expect(cards).toHaveCount(12)
  const search=page.getByRole('searchbox',{name:'Buscar condición o contexto'})
  await search.fill('Parkinson')
  await expect(cards).toHaveCount(1)
  await expect(cards.first().getByRole('heading',{name:/Neurología/i})).toBeVisible()
  await expect(cards.first().getByText('Parkinson')).toBeVisible()
  await search.fill('zzz___not_a_condition')
  await expect(cards).toHaveCount(0)
  await expect(page.getByText(/No aparece ese término/)).toBeVisible()
  await search.clear()
  await expect(cards).toHaveCount(12)
  await cards.first().getByRole('button',{name:/VER EJEMPLOS/}).click()
  await expect(cards.first().getByText('Escoliosis')).toBeVisible()
  await expect(page.getByText(/no significa que BAYONA trate esa patología/i)).toBeVisible()
  const metrics=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth-innerWidth}))
  expect(metrics.overflow).toBeLessThanOrEqual(1)
  expect(errors).toEqual([])
 })
 test('transparent journey in home / '+name,async({page})=>{
  await page.setViewportSize({width,height})
  await page.goto('/')
  const journey=page.locator('#tu-ruta')
  await expect(journey.getByRole('heading',{level:2})).toBeVisible()
  await expect(journey.getByText(/no se guardan, no se envían/i)).toBeVisible()
  const requests=[]
  page.on('request',r=>{if(['xhr','fetch','beacon'].includes(r.resourceType())&&r.method()==='POST')requests.push(r.url())})
  await journey.getByRole('button',{name:/Ganar fuerza/i}).click()
  await expect(journey.getByText('02 / TU CONTEXTO')).toBeVisible()
  await journey.getByRole('button',{name:/condición de salud diagnosticada/i}).click()
  await expect(journey.getByText('03 / TU RITMO')).toBeVisible()
  await journey.getByRole('button',{name:/Online y flexible/i}).click()
  await expect(journey.getByText(/YA TENEMOS UNA PRIMERA ORIENTACIÓN/)).toBeVisible()
  await expect(journey.getByText(/valoración y autorización/i)).toBeVisible()
  await expect(journey.getByText(/Tengo una condición de salud diagnosticada/)).toBeVisible()
  const links=await journey.locator('.bayona-discovery__result-links a').evaluateAll(nodes=>nodes.map(n=>n.href))
  expect(links[0]).toContain('/movimiento-adaptado')
  expect(links[1]).not.toMatch(/diagn[oó]stic|diabetes|condici[oó]n%20de%20salud/i)
  await journey.getByRole('button',{name:/BORRAR MIS RESPUESTAS/}).click()
  await expect(journey.getByText('01 / TU OBJETIVO')).toBeVisible()
  expect(requests).toEqual([])
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)
  expect(overflow).toBeLessThanOrEqual(1)
 })
}
